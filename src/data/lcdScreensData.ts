export function hasStationLcdScreens(station?: Station | null): boolean {
  if (!station) return false;
  if (station.hasLcdScreens === false) return false;
  if (station.isHeadquarters || station.stationCode === 'DALIOIL_010' || station.id === 10) return false;
  if (station.isTerminal) return false;
  return true;
}

