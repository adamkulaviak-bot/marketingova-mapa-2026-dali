export function getCurrentSpotAtTime(spots: LcdSpotItem[], currentTimeSec: number): LcdSpotItem | undefined {
  const normTime = currentTimeSec % (spots[spots.length - 1]?.endTime || 150);
  return spots.find((spot) => normTime >= spot.startTime && normTime < spot.endTime) || spots[0];
}
